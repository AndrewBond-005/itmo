# Константы кнопок
BUTTON_HELP_TEXT = "❓Помощь"
BUTTON_EXIT_TEXT = "Выход"
BUTTON_PADDING = 5

HELP_TEXT = """ СПРАВКА ПО ПРОГРАММЕ "Аппроксимация функции"

Программа строит несколько видов аппроксимирующих функций (линейная, квадратичная, кубическая, экспоненциальная, логарифмическая, степенная) по введённым точкам и выбирает лучшую.

1. ВВОД ДАННЫХ
   • Кликните в ячейку столбца X или Y.
   • Введите число (можно с точкой или запятой).
   • Нажмите Enter или кликните вне ячейки — значение сохранится и отформатируется.
   • Удалить строку — кнопка с корзиной справа.
   • Очистить все данные — кнопка с корзиной в заголовке таблицы.

2. РЕЖИМ ДОБАВЛЕНИЯ ТОЧЕК НА ГРАФИКЕ
   • Нажмите кнопку "Поставить точки" (она станет синей).
   • ЛКМ по графику — добавить точку в ближайшую свободную строку.
   • ПКМ по графику — удалить последнюю добавленную точку.
   • Повторное нажатие кнопки — выход из режима.

3. ВЫЧИСЛЕНИЕ АППРОКСИМАЦИИ
   • "Вычислить" — выполнить расчёт вручную.
   • "Автообновление" — расчёт при каждом изменении данных (кнопка горит синим).
   • Результаты: лучшая формула, сумма квадратов S, среднеквадратическое отклонение δ, коэффициент детерминации R², оценка качества.
   • В таблице результатов показаны все типы аппроксимаций.
   • Для выбранной функции в основной таблице заполняются столбцы φ(x) (расчётное значение) и ε (погрешность).

4. ИМПОРТ / ЭКСПОРТ
   • Импорт: текстовый файл (.txt) с парами чисел X и Y, разделённых пробелом или табуляцией. 
   • Экспорт: сохраняет текущую таблицу, лучшую аппроксимацию и все результаты в текстовый файл.

5. ДОПОЛНИТЕЛЬНО
   • Все расчёты выполняются методом наименьших квадратов.
   • Экспоненциальная, логарифмическая и степенная аппроксимации доступны только при положительных значениях X и/или Y.
"""

import tkinter as tk
from tkinter import ttk, messagebox


def setup_help_exit(parent, root):
    """Создаёт кнопки помощи и выхода."""
    frame = tk.Frame(parent)
    frame.pack(pady=BUTTON_PADDING)

    help_btn = tk.Button(
        frame,
        text=BUTTON_HELP_TEXT,
        bg="#f0f0f0",
        fg="black",
        command=lambda: messagebox.showinfo("Помощь", HELP_TEXT),
        relief=tk.RAISED,
        bd=2,
        padx=10,
        pady=2
    )
    help_btn.pack(side=tk.LEFT, padx=5)

    exit_btn = tk.Button(
        frame,
        text=BUTTON_EXIT_TEXT,
        bg="#ff1600",
        fg="black",
        command=root.quit,
        relief=tk.RAISED,
        bd=2,
        padx=10,
        pady=2
    )
    exit_btn.pack(side=tk.LEFT, padx=5)

    return frame