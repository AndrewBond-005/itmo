import tkinter as tk
from tkinter import ttk, scrolledtext


def show_help():
    """Создаёт и показывает окно помощи"""
    help_window = tk.Toplevel()
    help_window.title("Помощь - Интерполяция функций")
    help_window.geometry("550x500")
    help_window.minsize(400, 300)

    # Текст помощи
    help_text = """
ИНТЕРПОЛЯЦИЯ ФУНКЦИЙ

1. РАБОТА С ТАБЛИЦЕЙ УЗЛОВ
   • Добавить строку: кнопка "+ Добавить строку" под таблицей
   • Удалить строку: кнопка "🗑" в строке
   • Очистить всё: кнопка "🗑" в шапке таблицы (красная)
   • Редактировать: кликните на ячейку x или y, введите число, нажмите Enter

2. ВЗАИМОДЕЙСТВИЕ С ГРАФИКОМ (в режиме "Рисование")
   • ЛКМ (левая кнопка): добавить точку в месте клика
   • ПКМ (правая кнопка): удалить ближайшую точку
   • СКМ (нажатие колёсика): выбрать абсциссу (заполняет поле x)
   • Колёсико мыши: изменить Y ближайшей точки (шаг 0.1)

3. ИНТЕРПОЛЯЦИЯ
   • Три метода:
     - Лагранж (синий)
     - Ньютон (разделённые разности, зелёный)
     - Ньютон (конечные разности, оранжевый)
   • Включайте/выключайте методы соответствующими кнопками
   • Линии рисуются только при активном методе

4. АВТООБНОВЛЕНИЕ
   • Включено ("Авто"): линии и таблицы разностей пересчитываются при каждом изменении
   • Выключено: меняйте данные, линии не пересчитываются
   • При выключенном автообновлении используйте кнопку "Вычислить"

5. ВЫЧИСЛЕНИЕ В ТОЧКЕ
   • Введите x в поле, нажмите "Вычислить"
   • На графике появятся звёздочки (цвета методов)
   • Результаты выводятся в область сообщений

6. ГЕНЕРАЦИЯ ФУНКЦИИ
   • Введите формулу: sin(x), x**2, exp(x), log(x), sqrt(x) и т.д.
   • Поддерживаются: + - * / **, sin, cos, tan, log, ln, exp, sqrt, pi, E
   • Задайте интервал [a, b] и количество точек n (≥2)
   • Нажмите "Сгенерировать"

7. ИМПОРТ/ЭКСПОРТ
   • Импорт: загрузить узлы из txt/csv файла (формат: x y в строке)
   • Экспорт: сохранить текущие узлы в файл (формат: x.xxx y.xxx)
   • Разделители: пробел, табуляция или запятая

8. ОСИ ГРАФИКА
   • Фиксированы: X от -5 до 15, Y от -5 до 15
   • Точки за пределами не видны на графике
   • Используйте тулбар (внизу графика) для масштабирования и перемещения

9. ТАБЛИЦЫ РАЗНОСТЕЙ
   • Конечные разности: работают только при равномерном шаге
   • Разделённые разности: работают всегда (при ≥2 точках)
   • Отображаются в нижней части левой панели

10. ОБЛАСТЬ СООБЩЕНИЙ
   • Все ошибки и предупреждения выводятся здесь
   • Информационные сообщения о действиях
"""

    # Создаём текстовое поле с прокруткой
    text_area = scrolledtext.ScrolledText(help_window, wrap=tk.WORD, font=("Helvetica", 11))
    text_area.pack(fill=tk.BOTH, expand=True, padx=10, pady=10)
    text_area.insert(tk.INSERT, help_text)
    text_area.config(state=tk.DISABLED)

    # Кнопка закрытия
    close_btn = ttk.Button(help_window, text="Закрыть", command=help_window.destroy)
    close_btn.pack(pady=(0, 10))

    # Центрируем окно
    help_window.update_idletasks()
    width = help_window.winfo_width()
    height = help_window.winfo_height()
    x = (help_window.winfo_screenwidth() // 2) - (width // 2)
    y = (help_window.winfo_screenheight() // 2) - (height // 2)
    help_window.geometry(f"{width}x{height}+{x}+{y}")